// Контент лунного календаря: шрифт 5x7, иконки сфер, таблица дней.
// Шрифт свой, потому что во встроенных шрифтах LovyanGFX нет кириллицы.
//
// Маски сфер собраны из корпуса zet/corpus.jsonl: 210 текстов, семь авторов
// (Глоба в двух книгах, Зараев, Альберт Великий, ведические титхи, хорарная
// традиция). Для каждой сферы считается полярность упоминаний по предложениям
// с проверкой отрицаний рядом с ключевым словом, затем z-оценка по всем
// тридцати дням: важна не частота темы, а насколько день по ней выделяется.
// Без нормализации «дела» побеждали в двадцати шести днях из тридцати просто
// потому, что слово частое.
//
// Четыре сферы — фокус, ошибки, изобретение, разбор — сопоставлены с
// качествами дня, а не с прямыми упоминаниями: авторы описывают ясность ума,
// склонность к путанице, тягу к уединению, и это отображено на современную
// работу. Где авторы расходятся, берётся перевес.

